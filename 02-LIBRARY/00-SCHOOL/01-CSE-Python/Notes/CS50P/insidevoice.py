# Goal: Ask the user for text and print it back in lowercase
# Given: The user types a sentence
# Find: The same sentence converted to lowercase
# Step 1: Ask the user for input and store it in a variable
text = input("Can I have some text please? ")
# Step 2: Convert the stored text to lowercase
lowercase_text = text.lower()
# Step 3: Print the lowercase result
print(lowercase_text)
